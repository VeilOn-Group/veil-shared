// Package tokens loads design-tokens.json, checks WCAG contrast
// and generates CSS variables, a Tailwind v4 theme and Kotlin colors.
package tokens

import (
	"encoding/json"
	"fmt"
	"math"
	"sort"
	"strconv"
	"strings"

	veilshared "github.com/veilon/veil-shared"
)

// Tokens mirrors design-tokens.json.
type Tokens struct {
	Theme    string            `json:"theme"`
	Color    map[string]string `json:"color"`
	Effect   map[string]string `json:"effect"`
	Font     map[string]string `json:"font"`
	Radius   map[string]string `json:"radius"`
	Contrast struct {
		Text [][2]string `json:"text"` // >= 4.5:1 (WCAG AA normal text)
		UI   [][2]string `json:"ui"`   // >= 3:1 (WCAG 1.4.11 non-text)
	} `json:"contrast"`
}

// Minimum ratios.
const (
	MinTextContrast = 4.5
	MinUIContrast   = 3.0
)

// Parse decodes tokens.
func Parse(data []byte) (*Tokens, error) {
	var t Tokens
	dec := json.NewDecoder(strings.NewReader(string(data)))
	if err := dec.Decode(&t); err != nil {
		return nil, fmt.Errorf("tokens: %w", err)
	}
	if t.Theme != "dark" {
		return nil, fmt.Errorf("tokens: only the dark theme is supported")
	}
	for k, v := range t.Color {
		if _, err := ParseHex(v); err != nil {
			return nil, fmt.Errorf("tokens: color %s: %w", k, err)
		}
	}
	return &t, nil
}

// Embedded returns the compiled-in tokens.
func Embedded() (*Tokens, error) { return Parse(veilshared.DesignTokensJSON) }

// RGB is an sRGB color.
type RGB struct{ R, G, B uint8 }

// ParseHex parses #RRGGBB.
func ParseHex(s string) (RGB, error) {
	if len(s) != 7 || s[0] != '#' {
		return RGB{}, fmt.Errorf("want #RRGGBB, got %q", s)
	}
	v, err := strconv.ParseUint(s[1:], 16, 32)
	if err != nil {
		return RGB{}, err
	}
	return RGB{uint8(v >> 16), uint8(v >> 8), uint8(v)}, nil //nolint:gosec // v < 2^24 (6 hex digits)
}

func channel(c uint8) float64 {
	v := float64(c) / 255
	if v <= 0.04045 {
		return v / 12.92
	}
	return math.Pow((v+0.055)/1.055, 2.4)
}

// Luminance is WCAG relative luminance.
func (c RGB) Luminance() float64 {
	return 0.2126*channel(c.R) + 0.7152*channel(c.G) + 0.0722*channel(c.B)
}

// Contrast returns the WCAG contrast ratio.
func Contrast(a, b RGB) float64 {
	la, lb := a.Luminance(), b.Luminance()
	if la < lb {
		la, lb = lb, la
	}
	return (la + 0.05) / (lb + 0.05)
}

// Violation describes a failing pair.
type Violation struct {
	FG, BG string
	Ratio  float64
	Min    float64
}

// CheckContrast verifies all declared pairs.
func (t *Tokens) CheckContrast() ([]Violation, error) {
	var out []Violation
	check := func(pairs [][2]string, min float64) error {
		for _, p := range pairs {
			fg, ok1 := t.Color[p[0]]
			bg, ok2 := t.Color[p[1]]
			if !ok1 || !ok2 {
				return fmt.Errorf("tokens: contrast pair %v references unknown color", p)
			}
			a, _ := ParseHex(fg)
			b, _ := ParseHex(bg)
			if r := Contrast(a, b); r < min {
				out = append(out, Violation{p[0], p[1], r, min})
			}
		}
		return nil
	}
	if err := check(t.Contrast.Text, MinTextContrast); err != nil {
		return nil, err
	}
	if err := check(t.Contrast.UI, MinUIContrast); err != nil {
		return nil, err
	}
	return out, nil
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// CSS returns :root variables (--veil-*) plus a Tailwind v4 @theme block that
// maps utilities (bg-bg-base, text-text-muted, ...) to those variables.
func (t *Tokens) CSS() string {
	var b strings.Builder
	b.WriteString(mplCSS + "/* Code generated by veil-shared/cmd/tokensgen. DO NOT EDIT. */\n:root {\n  color-scheme: dark;\n")
	for _, k := range sortedKeys(t.Color) {
		fmt.Fprintf(&b, "  --veil-%s: %s;\n", k, t.Color[k])
	}
	for _, k := range sortedKeys(t.Effect) {
		fmt.Fprintf(&b, "  --veil-%s: %s;\n", k, t.Effect[k])
	}
	for _, k := range sortedKeys(t.Font) {
		fmt.Fprintf(&b, "  --veil-font-%s: %s;\n", k, t.Font[k])
	}
	for _, k := range sortedKeys(t.Radius) {
		fmt.Fprintf(&b, "  --veil-radius-%s: %s;\n", k, t.Radius[k])
	}
	b.WriteString("}\n")
	return b.String()
}

// TailwindTheme returns a Tailwind v4 "@theme inline" block.
func (t *Tokens) TailwindTheme() string {
	var b strings.Builder
	b.WriteString(mplCSS + "/* Code generated by veil-shared/cmd/tokensgen. DO NOT EDIT. */\n@theme inline {\n")
	for _, k := range sortedKeys(t.Color) {
		fmt.Fprintf(&b, "  --color-%s: var(--veil-%s);\n", k, k)
	}
	fmt.Fprintf(&b, "  --font-sans: var(--veil-font-ui);\n  --font-mono: var(--veil-font-mono);\n")
	for _, k := range sortedKeys(t.Radius) {
		fmt.Fprintf(&b, "  --radius-%s: var(--veil-radius-%s);\n", k, k)
	}
	b.WriteString("}\n")
	return b.String()
}

// Kotlin returns a Compose color object for the Android app.
func (t *Tokens) Kotlin() string {
	var b strings.Builder
	b.WriteString(mplLine + "// Code generated by veil-shared/cmd/tokensgen. DO NOT EDIT.\npackage net.veilon.app.ui.theme\n\nimport androidx.compose.ui.graphics.Color\n\nobject VeilColors {\n")
	for _, k := range sortedKeys(t.Color) {
		c, _ := ParseHex(t.Color[k])
		fmt.Fprintf(&b, "    val %s = Color(0xFF%02X%02X%02X)\n", kotlinName(k), c.R, c.G, c.B)
	}
	b.WriteString("}\n")
	return b.String()
}

func kotlinName(k string) string {
	parts := strings.Split(k, "-")
	for i := 1; i < len(parts); i++ {
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	return strings.Join(parts, "")
}

