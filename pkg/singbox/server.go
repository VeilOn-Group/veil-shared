// Node inbound tags.
const (
	TagInNaive     = "naive-in"
	TagInHysteria2 = "hy2-in"
)

// NodeSpec is the sing-box part of a node. VLESS runs
// in Xray, which owns the public TCP port (REALITY); sing-box serves:
//
//	127.0.0.1:NaivePort/tcp  naive inbound (HTTP/2, TCP only), with the node
//	          certificate. It is the REALITY target: unauthenticated TLS on
//	          :443 (naive clients, probes) reaches it ("steal-self").
//	:UDPPort/udp  Hysteria 2 (salamander by default), same certificate.
type NodeSpec struct {
	Domain    string // node domain: TLS server name of naive and hysteria2
	Listen    string // public listen address, e.g. "0.0.0.0" or "::"
	UDPPort   uint16 // usually 443
	NaivePort uint16 // loopback port of the naive inbound, e.g. 8444

	CertPath string // PEM certificate chain for Domain
	KeyPath  string // PEM private key

	Hy2ObfsPassword string
	Hy2UpMbps       int
	Hy2DownMbps     int
	Hy2Masquerade   string // optional URL served to non-Hysteria HTTP/3 clients
	// Hy2NoObfs switches the salamander obfuscation off (plain QUIC looks
	// like HTTP/3, obfuscated QUIC looks like random UDP: an operator
	// choice per network).
	Hy2NoObfs                bool
	Hy2IgnoreClientBandwidth bool

	// StatsListen enables per-user traffic counters (custom node build with
	// with_v2ray_api). Must be a loopback address.
	StatsListen string

	// BlockPorts are rejected for outgoing TCP (anti-abuse, e.g. 25).
	BlockPorts []uint16
	// AllowCIDRs are private destinations users may reach (test benches
	// only). Every other private, loopback or link-local destination is
	// rejected, like Xray does for VLESS (no access to the node's networks).
	AllowCIDRs []string

	// DisableHysteria2 removes the UDP inbound. A disabled naive keeps its
	// inbound (it is the REALITY target) with only the placeholder user.
	DisableHysteria2, DisableNaive bool

	// PlaceholderPassword is a random secret generated by the agent. sing-box
	// refuses a naive inbound without users, so when naive has none (no
	// subscribers yet, or naive disabled) a placeholder user with this
	// password keeps the steal-self front working without opening a proxy.
	PlaceholderPassword string
}

// PlaceholderUser is the naive user name used with PlaceholderPassword.
const PlaceholderUser = "_placeholder"

// NodeUser is one subscriber as seen by a node: a node-scoped pseudonym and
// transport credentials; never the account id.
type NodeUser struct {
	Pseudonym     string `json:"pseudonym"`
	VLESSUUID     string `json:"vless_uuid"`
	Hy2Password   string `json:"hy2_password"`
	NaivePassword string `json:"naive_password"`
}

// ErrNodeSpec reports an invalid node specification.
var ErrNodeSpec = errors.New("singbox: invalid node spec")

