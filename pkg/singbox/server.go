// DefaultServerTemplate is the node sing-box template used unless the
// operator saved a custom one.
func DefaultServerTemplate() tmpl.Doc {
	t := tmpl.Token
	return tmpl.Doc{
		"log": map[string]any{"disabled": true},
		"inbounds": []any{
			map[string]any{
				"type": "naive", "tag": TagInNaive, "listen": "127.0.0.1", "listen_port": t("naive_port"),
				"network": "tcp", "users": t("users_naive"),
				"tls": map[string]any{
					"enabled": true, "server_name": t("domain"),
					"certificate_path": t("tls_certificate_path"), "key_path": t("tls_key_path"),
				},
			},
			map[string]any{
				tmpl.When: "hy2_enabled",
				"type":    "hysteria2", "tag": TagInHysteria2, "listen": t("listen"), "listen_port": t("udp_port"),
				"users":   t("users_hy2"),
				"up_mbps": t("hy2_up_mbps"), "down_mbps": t("hy2_down_mbps"),
				"ignore_client_bandwidth": t("hy2_ignore_client_bandwidth"),
				"obfs":                    t("hy2_obfs"), "masquerade": t("hy2_masquerade"),
				"tls": map[string]any{
					"enabled": true, "server_name": t("domain"), "alpn": []any{"h3"},
					"certificate_path": t("tls_certificate_path"), "key_path": t("tls_key_path"),
				},
			},
		},
		"outbounds":    []any{map[string]any{"type": "direct", "tag": TagDirect}},
		"route":        map[string]any{"rules": t("route_rules"), "final": TagDirect},
		"experimental": map[string]any{"v2ray_api": t("stats_api")},
	}
}

// ServerValues computes the token values for spec and users.
func ServerValues(spec NodeSpec, users []NodeUser) (map[string]any, error) {
	if err := spec.validate(); err != nil {
		return nil, err
	}
	us := append([]NodeUser(nil), users...)
	sort.Slice(us, func(i, j int) bool { return us[i].Pseudonym < us[j].Pseudonym })
	hy2, naive := []any{}, []any{}
	var statUsers []any
	seen := map[string]bool{}
	for _, u := range us {
		if u.Pseudonym == "" || u.Pseudonym == PlaceholderUser || seen[u.Pseudonym] {
			return nil, fmt.Errorf("%w: empty or duplicate pseudonym", ErrNodeSpec)
		}
		seen[u.Pseudonym] = true
		if !spec.DisableHysteria2 {
			hy2 = append(hy2, map[string]any{"name": u.Pseudonym, "password": u.Hy2Password})
		}
		if !spec.DisableNaive {
			naive = append(naive, map[string]any{"username": u.Pseudonym, "password": u.NaivePassword})
		}
		statUsers = append(statUsers, u.Pseudonym)
	}
	if len(naive) == 0 {
		if len(spec.PlaceholderPassword) < 16 {
			return nil, fmt.Errorf("%w: naive has no users and no placeholder password (>= 16 chars)", ErrNodeSpec)
		}
		naive = []any{map[string]any{"username": PlaceholderUser, "password": spec.PlaceholderPassword}}
	}
	obfs := tmpl.Omit
	if !spec.Hy2NoObfs {
		obfs = map[string]any{"type": "salamander", "password": spec.Hy2ObfsPassword}
	}
	masq := tmpl.Omit
	if spec.Hy2Masquerade != "" {
		masq = spec.Hy2Masquerade
	}
	rules := []any{}
	if len(spec.BlockPorts) > 0 {
		ps := make([]any, 0, len(spec.BlockPorts))
		for _, p := range spec.BlockPorts {
			ps = append(ps, int(p))
		}
		rules = append(rules, map[string]any{"network": "tcp", "port": ps, "action": "reject"})
	}
	// Resolve first so the address rules also catch names that point to
	// private addresses (e.g. "localhost").
	rules = append(rules, map[string]any{"action": "resolve"})
	if len(spec.AllowCIDRs) > 0 {
		cs := make([]any, 0, len(spec.AllowCIDRs))
		for _, c := range spec.AllowCIDRs {
			cs = append(cs, c)
		}
		rules = append(rules, map[string]any{"ip_cidr": cs, "outbound": TagDirect})
	}
	rules = append(rules, map[string]any{"ip_is_private": true, "action": "reject"})
	stats := tmpl.Omit
	if spec.StatsListen != "" {
		if statUsers == nil {
			statUsers = []any{}
		}
		stats = map[string]any{"listen": spec.StatsListen, "stats": map[string]any{"enabled": true, "users": statUsers}}
	}
	return map[string]any{
		"listen": spec.Listen, "domain": spec.Domain,
		"naive_port": int(spec.NaivePort), "udp_port": int(spec.UDPPort),
		"tls_certificate_path": spec.CertPath, "tls_key_path": spec.KeyPath,
		"users_naive": naive, "users_hy2": hy2, "hy2_enabled": !spec.DisableHysteria2,
		"hy2_up_mbps": spec.Hy2UpMbps, "hy2_down_mbps": spec.Hy2DownMbps,
		"hy2_ignore_client_bandwidth": spec.Hy2IgnoreClientBandwidth,
		"hy2_obfs":                    obfs, "hy2_masquerade": masq,
		"route_rules": rules, "stats_api": stats,
	}, nil
}

// BuildServer renders the node sing-box config from a template (nil =
// default). Users are sorted for deterministic output (stable reloads and
// golden tests). An empty "experimental" object is dropped.
func BuildServer(template tmpl.Doc, spec NodeSpec, users []NodeUser) (tmpl.Doc, error) {
	if template == nil {
		template = DefaultServerTemplate()
	}
	vals, err := ServerValues(spec, users)
	if err != nil {
		return nil, err
	}
	doc, err := tmpl.Render(template, vals)
	if err != nil {
		return nil, err
	}
	if e, ok := doc["experimental"].(map[string]any); ok && len(e) == 0 {
		delete(doc, "experimental")
	}
	if err := AssertServerNoLog(doc); err != nil {
		return nil, err
	}
	return doc, nil
}

func (s NodeSpec) validate() error {
	var errs []string
	if s.Domain == "" || strings.ContainsAny(s.Domain, " /:") {
		errs = append(errs, "domain")
	}
	if s.UDPPort == 0 || s.NaivePort == 0 {
		errs = append(errs, "ports")
	}
	if s.CertPath == "" || s.KeyPath == "" {
		errs = append(errs, "certificate")
	}
	if s.Hy2ObfsPassword == "" && !s.DisableHysteria2 && !s.Hy2NoObfs {
		errs = append(errs, "hysteria2 obfs")
	}
	if s.StatsListen != "" && !strings.HasPrefix(s.StatsListen, "127.0.0.1:") {
		errs = append(errs, "stats must listen on 127.0.0.1")
	}
	for _, c := range s.AllowCIDRs {
		if _, err := netip.ParsePrefix(c); err != nil {
			errs = append(errs, "allow cidr "+c)
		}
	}
	if len(errs) > 0 {
		return fmt.Errorf("%w: %s", ErrNodeSpec, strings.Join(errs, ", "))
	}
	return nil
}
