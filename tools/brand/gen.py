"""Generate every VeilOn brand asset from the single master mark
(veil-shared/brand/src/veilon-mark.svg). Requires: rsvg-convert, Pillow,
png2icns (icnsutils). Output: veil-shared/brand/dist (committed).

The master was traced from the original raster, made exactly mirror-symmetric
and centered (axis 500.00/1000, left/right margins equal)."""
import os, re, subprocess, sys
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "brand", "src", "veilon-mark.svg")
OUT = os.path.join(ROOT, "brand", "dist")
os.makedirs(OUT, exist_ok=True)

master = open(SRC).read()
path = re.search(r' d="([^"]+)"', master).group(1)
GRAD = ('<linearGradient id="vg" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="0" y2="1000">'
        '<stop offset="0" stop-color="#7419A5"/><stop offset=".47" stop-color="#A048C8"/>'
        '<stop offset="1" stop-color="#C514C0"/></linearGradient>')

def write(name, text):
    with open(os.path.join(OUT, name), "w") as f:
        f.write(text)

def mark_in(size, scale, bg=None, radius=0.225, glow=True):
    """Mark centered on a square canvas; scale = mark size / canvas."""
    m = scale * size; off = (size - m) / 2; k = m / 1000
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}"><defs>{GRAD}'
             '<radialGradient id="gl" cx="50%" cy="50%" r="50%"><stop offset="0" stop-color="#8B5CF6" stop-opacity=".22"/>'
             '<stop offset="1" stop-color="#8B5CF6" stop-opacity="0"/></radialGradient></defs>']
    if bg:
        rx = f' rx="{size*radius:.1f}"' if radius else ""
        parts.append(f'<rect width="{size}" height="{size}"{rx} fill="{bg}"/>')
        if glow:
            parts.append(f'<rect width="{size}" height="{size}"{rx} fill="url(#gl)"/>')
    parts.append(f'<g transform="translate({off:.3f} {off:.3f}) scale({k:.6f})"><path fill="url(#vg)" d="{path}"/></g></svg>\n')
    return "".join(parts)

def render(svg_name, png_name, px):
    subprocess.run(["rsvg-convert", "-w", str(px), "-h", str(px), os.path.join(OUT, svg_name),
                    "-o", os.path.join(OUT, png_name)], check=True)

# 1) Vector assets
write("veilon-mark.svg", master)                                   # tight, transparent
write("veilon-mark-padded.svg", mark_in(1000, 0.8))                # transparent, 10% padding
write("veilon-app-icon.svg", mark_in(1024, 0.62, bg="#0A0A0F"))    # dark rounded square
write("veilon-app-icon-square.svg", mark_in(1024, 0.62, bg="#0A0A0F", radius=0))
# Monochrome (tray/menu bar): currentColor, no gradient.
write("veilon-mark-mono.svg", f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000"><path fill="currentColor" d="{path}"/></svg>\n')

# 2) PNGs
sizes = [16, 24, 32, 48, 64, 128, 256, 512, 1024]
for s in sizes:
    render("veilon-app-icon.svg", f"icon-{s}.png", s)
for s in [32, 64, 128, 256, 512]:
    render("veilon-mark-padded.svg", f"mark-{s}.png", s)

# 3) Windows .ico and favicon (square variant reads better at 16 px)
imgs = []
for s in [16, 24, 32, 48, 64, 128, 256]:
    render("veilon-app-icon-square.svg" if s <= 32 else "veilon-app-icon.svg", f"_ico-{s}.png", s)
    imgs.append(Image.open(os.path.join(OUT, f"_ico-{s}.png")).convert("RGBA"))
imgs[-1].save(os.path.join(OUT, "veilon.ico"), sizes=[(i.width, i.height) for i in imgs], append_images=imgs[:-1])
imgs[2].save(os.path.join(OUT, "favicon.ico"), sizes=[(16, 16), (32, 32), (48, 48)], append_images=[imgs[0], imgs[3]])
for s in [16, 24, 32, 48, 64, 128, 256]:
    os.remove(os.path.join(OUT, f"_ico-{s}.png"))

# 4) macOS .icns
icns_in = [os.path.join(OUT, f"icon-{s}.png") for s in [16, 32, 128, 256, 512, 1024]]
subprocess.run(["png2icns", os.path.join(OUT, "veilon.icns")] + icns_in, check=True, stdout=subprocess.DEVNULL)

# 5) Android adaptive icon foreground (VectorDrawable, 108dp canvas, safe zone 66dp)
#    VectorDrawable pathData accepts SVG path syntax; gradient via aapt:attr (API 24+).
k = 0.058  # 1000 units -> 58dp (fits the 66dp safe zone with margin)
off = (108 - 1000 * k) / 2
write("ic_launcher_foreground.xml", f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/gen.py. DO NOT EDIT. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
  <group android:translateX="{off:.3f}" android:translateY="{off:.3f}" android:scaleX="{k}" android:scaleY="{k}">
    <path android:pathData="{path}">
      <aapt:attr name="android:fillColor">
        <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="0" android:endY="1000">
          <item android:offset="0" android:color="#FF7419A5"/>
          <item android:offset="0.47" android:color="#FFA048C8"/>
          <item android:offset="1" android:color="#FFC514C0"/>
        </gradient>
      </aapt:attr>
    </path>
  </group>
</vector>
''')
write("ic_launcher_monochrome.xml", f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/gen.py. DO NOT EDIT. Themed icon (Android 13+). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
  <group android:translateX="{off:.3f}" android:translateY="{off:.3f}" android:scaleX="{k}" android:scaleY="{k}">
    <path android:fillColor="#FFFFFFFF" android:pathData="{path}"/>
  </group>
</vector>
''')
for d, s in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
    render("veilon-app-icon-square.svg", f"android-{d}.png", s)
print("brand assets:", len(os.listdir(OUT)))
